#!/usr/bin/env python3

from glob import glob
import os

HEAD_SIZES_KQ = [40, 64, 72, 80, 96, 112, 128, 192, 256, 320, 512, 576]

# DKQ -> DV override for asymmetric head dims.
HEAD_SIZES_V_OVERRIDE = {576: 512, 320: 256, 192: 128}

TYPES_KV = ["GGML_TYPE_F16", "GGML_TYPE_Q4_0", "GGML_TYPE_Q4_1", "GGML_TYPE_Q5_0", "GGML_TYPE_Q5_1", "GGML_TYPE_Q8_0", "GGML_TYPE_BF16", "GGML_TYPE_IQ4_NL"]

SOURCE_FATTN_TILE = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../fattn-tile.cuh"

DECL_FATTN_TILE_CASE_TYPE({head_size_kq}, {head_size_v}, {type_kv});
"""

SOURCE_FATTN_VEC = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../fattn-vec.cuh"

DECL_FATTN_VEC_CASE( 64, {type_k}, {type_v});
DECL_FATTN_VEC_CASE(128, {type_k}, {type_v});
DECL_FATTN_VEC_CASE(256, {type_k}, {type_v});
"""

SOURCE_FATTN_MMA_START = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../fattn-mma-f16.cuh"

"""

SOURCE_FATTN_MMA_CASE = "DECL_FATTN_MMA_F16_CASE({head_size_kq}, {head_size_v}, {ncols1}, {ncols2});\n"

SOURCE_FATTN_MMA_BAND_FETCH_AHEAD = """#if defined(GGML_USE_HIP)
DECL_FATTN_MMA_F16_BAND_FETCH_AHEAD(256, 256, {ncols1}, 8);
#endif // defined(GGML_USE_HIP)
"""

# The W = 5..8 64-column block of the RDNA4 band runs in the band's own geometry (band_wide), so it is a
# case instantiation of its own (see ggml_cuda_fattn_mma_get_config_rdna): prefill keeps the 256-thread
# table row, the band keeps the 16-warp row that splits the KV rows like the 32-column block does.
SOURCE_FATTN_MMA_BAND_WIDE_CASE = """#if defined(GGML_USE_HIP)
DECL_FATTN_MMA_F16_BAND_WIDE_CASE(256, 256, 8, 8);
#endif // defined(GGML_USE_HIP)
"""

SOURCE_FATTN_MMA_BAND_WIDE_FETCH_AHEAD = """#if defined(GGML_USE_HIP)
DECL_FATTN_MMA_F16_BAND_WIDE_FETCH_AHEAD(256, 256, 8, 8);
#endif // defined(GGML_USE_HIP)
"""

TYPES_MMQ = [
    "GGML_TYPE_Q1_0",
    "GGML_TYPE_Q2_0",
    "GGML_TYPE_Q4_0", "GGML_TYPE_Q4_1", "GGML_TYPE_Q5_0", "GGML_TYPE_Q5_1", "GGML_TYPE_Q8_0",
    "GGML_TYPE_Q2_K", "GGML_TYPE_Q3_K", "GGML_TYPE_Q4_K", "GGML_TYPE_Q5_K", "GGML_TYPE_Q6_K",
    "GGML_TYPE_IQ2_XXS", "GGML_TYPE_IQ2_XS", "GGML_TYPE_IQ2_S", "GGML_TYPE_IQ3_XXS", "GGML_TYPE_IQ3_S",
    "GGML_TYPE_IQ1_S", "GGML_TYPE_IQ4_NL", "GGML_TYPE_IQ4_XS", "GGML_TYPE_MXFP4", "GGML_TYPE_NVFP4"
]

SOURCE_MMQ = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../mmq.cuh"

DECL_MMQ_CASE({type});
"""

TYPES_MMQ_W4A4 = ["GGML_TYPE_MXFP4", "GGML_TYPE_NVFP4"]

SOURCE_MMQ_W4A4 = """
DECL_MMQ_CASE_W4A4({type});
"""
# fused gate+up+GLU MMQ kernel: enabled types (Q6_K first, extend as validated)
MMQ_GATE_TYPES = ["GGML_TYPE_Q3_K", "GGML_TYPE_Q4_K", "GGML_TYPE_Q5_K", "GGML_TYPE_Q8_0", "GGML_TYPE_Q6_K"]

# Appended to the matching mmq-instance file, so it must not repeat the header/include.
SOURCE_MMQ_GATE = "DECL_MMQ_CASE_GATE({type});\n"

SOURCE_MMF = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../mmf.cuh"

DECL_MMF_CASE({type});
"""


def get_short_name(long_quant_name):
    return long_quant_name.replace("GGML_TYPE_", "").lower()


for filename in glob("*.cu"):
    os.remove(filename)

# One translation unit per (head size, KV type) instead of one per head size.  The emitted
# instantiations are exactly the same 12 x 8 cases; the tile kernel is instantiated per type, so
# the 8-case files were up to 14.8 MB / 137 s and one of them gated the backend build.  CMake
# globs template-instances/fattn-tile*.cu, so no CMake change is needed.
for head_size_kq in HEAD_SIZES_KQ:
    head_size_v = HEAD_SIZES_V_OVERRIDE.get(head_size_kq, head_size_kq)
    for type_kv in TYPES_KV:
        with open(f"fattn-tile-instance-dkq{head_size_kq}-dv{head_size_v}-{get_short_name(type_kv)}.cu", "w") as f:
            f.write(SOURCE_FATTN_TILE.format(head_size_kq=head_size_kq, head_size_v=head_size_v, type_kv=type_kv))

for type_k in TYPES_KV:
    for type_v in TYPES_KV:
        with open(f"fattn-vec-instance-{get_short_name(type_k)}-{get_short_name(type_v)}.cu", "w") as f:
            f.write(SOURCE_FATTN_VEC.format(type_k=type_k, type_v=type_v))

for ncols in [8, 16, 32, 64]:
    for ncols2 in [1, 2, 4, 8, 16, 32]:
        if ncols2 > ncols:
            continue
        ncols1 = ncols // ncols2

        # One translation unit per (ncols1, ncols2, head size) instead of one per
        # (ncols1, ncols2).  The set of emitted template instantiations is exactly the
        # same; only their grouping changes, so this is build-time only (the native-KV
        # arm chain in fattn-mma-f16.cuh duplicates the whole WMMA kernel per KV type,
        # which made the 8-case files ~200 s each and the backend build one-file-bound).
        # CMake globs template-instances/fattn-mma*.cu, so no CMake change is needed.
        for head_size_kq in HEAD_SIZES_KQ:
            if head_size_kq == 40:
                continue
            if head_size_kq == 72:
                continue
            # Skip compilation of unused ncols2 values for niche head sizes:
            if head_size_kq == 192 and ncols2 not in (8, 16): # MiMo-V2.5
                continue
            if head_size_kq == 320 and ncols2 != 32: # Mistral Small 4
                continue
            if head_size_kq == 512 and ncols2 not in (2, 4, 8): # Gemma 4 (+ MTP)
                continue
            if head_size_kq == 576 and ncols2 not in (4, 16, 32): # Deepseek, GLM 4.7 Flash
                continue
            if head_size_kq not in (192, 320, 576) and ncols2 in (16, 32):
                continue
            head_size_v = HEAD_SIZES_V_OVERRIDE.get(head_size_kq, head_size_kq)
            with open(f"fattn-mma-f16-instance-ncols1_{ncols1}-ncols2_{ncols2}-dkq{head_size_kq}-dv{head_size_v}.cu", "w") as f:
                f.write(SOURCE_FATTN_MMA_START)
                f.write(SOURCE_FATTN_MMA_CASE.format(ncols1=ncols1, ncols2=ncols2, head_size_kq=head_size_kq, head_size_v=head_size_v))

# The q8_0 fetch-ahead variants of the RDNA4 band kernel, each in a translation unit of its own (see
# ggml_cuda_flash_attn_ext_mma_f16_band_fetch_ahead_kernel in fattn-mma-f16.cuh).
for ncols1 in [4, 8]:
    with open(f"fattn-mma-f16-band-fetch-ahead-ncols1_{ncols1}-ncols2_8-dkq256-dv256.cu", "w") as f:
        f.write(SOURCE_FATTN_MMA_START)
        f.write(SOURCE_FATTN_MMA_BAND_FETCH_AHEAD.format(ncols1=ncols1))

# The band's own 64-column block (query widths 5..8), also one translation unit per kernel variant.
with open("fattn-mma-f16-band-wide-ncols1_8-ncols2_8-dkq256-dv256.cu", "w") as f:
    f.write(SOURCE_FATTN_MMA_START)
    f.write(SOURCE_FATTN_MMA_BAND_WIDE_CASE)
with open("fattn-mma-f16-band-wide-fetch-ahead-ncols1_8-ncols2_8-dkq256-dv256.cu", "w") as f:
    f.write(SOURCE_FATTN_MMA_START)
    f.write(SOURCE_FATTN_MMA_BAND_WIDE_FETCH_AHEAD)

for type in TYPES_MMQ:
    with open(f"mmq-instance-{get_short_name(type)}.cu", "w") as f:
        f.write(SOURCE_MMQ.format(type=type))
        if type in TYPES_MMQ_W4A4:
            f.write(SOURCE_MMQ_W4A4.format(type=type))

for type in MMQ_GATE_TYPES:
    with open(f"mmq-instance-{get_short_name(type)}.cu", "a") as f:
        f.write(SOURCE_MMQ_GATE.format(type=type))

for type in range(1, 17):
    with open(f"mmf-instance-ncols_{type}.cu", "w") as f:
        f.write(SOURCE_MMF.format(type=type))
